/**
 * ## 读"代码"而不是"注释"：守卫的公共助手
 *
 * 这个项目里已经**六次**出现"守卫被自己的注释骗到"：
 * 文档里提到 `list-style-image`、`alert()`、`POLL_MAX_MS`、`<select>`……
 * 于是"代码里有没有 X"的判断在**注释满足**的情况下永远为真 —— 假绿。
 *
 * 所以凡是要判断"代码里有没有 / 顺序如何"的守卫，都必须先剥注释。
 *
 * ## ⚠️ 顺序很关键：**先剥行注释，再剥块注释**
 *
 * 反过来的话，一条普通的行注释就能骗过块注释正则。真实案例：
 *
 * ```ts
 * // Zotero 自己的图标是 chrome://zotero/skin/16/universal/*.svg
 * ```
 *
 * 这行里的 `universal` + 斜杠 + 星号 + `.svg` 含有**块注释的起始序列**，
 * 块注释正则从那里开始，一路吃到下一个**闭合序列**，把中间 2000 多个字符的
 * 真实代码全删了。于是守卫在"代码"里找不到 `list-style-image`，
 * 报出一个**假的失败**（比假绿更难查：假绿是漏报，假红是误导）。
 *
 * ⚠️ 写这段说明时我自己踩了同一个坑：注释里出现那个**两字符闭合序列**，
 * 会把这篇文档注释提前结束，剩下的说明文字变成"代码" → 整个文件语法错。
 * 所以这里用文字描述代替那两个字符。
 *
 * 先剥行注释就不会有这个问题：行注释整行消失，起始序列也就不存在了。
 *
 * ## 它不处理什么
 *
 * 不剥字符串字面量 —— 若某个守卫要判断的东西恰好出现在字符串里，
 * 需要自己再处理。注释与字符串的完整解析应该交给编译器，
 * 这里只是给"读源码做断言"这类守卫一个够用的近似。
 */

/**
 * 去掉 TypeScript/JavaScript 源码里的注释。
 *
 * @param source 源码全文
 * @returns 只剩代码的文本（换行保留，便于按顺序判断）
 */
export function codeOnly(source) {
  return (
    String(source ?? "")
      // ① 先剥整行注释：它们里面可能含 `/*` 序列，会骗过下一步
      .replace(/^[ \t]*\/\/.*$/gm, "")
      // ② 再剥块注释（含 JSDoc）
      .replace(/\/\*[\s\S]*?\*\//g, "")
  );
}

/**
 * 去掉 XHTML/HTML 里的注释（用于"页面里有没有某个元素"这类守卫）。
 *
 * 与 {@link codeOnly} 同样的道理：说明文字里提到 `<select>` 不等于真的用了它。
 */
export function markupOnly(source) {
  return String(source ?? "").replace(/<!--[\s\S]*?-->/g, "");
}
